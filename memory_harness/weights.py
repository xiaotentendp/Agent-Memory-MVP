"""
【这个文件干什么】
把所有的"数值游戏规则"集中写在一起。
以后想调参（比如让扣分更狠一点），只改这个文件，别的都不用动。
"""

# 新经验的初始权重，满分 1.0（可以理解成"这条经验现在的可信度是 100 分"）
INIT_W = 1.0

# 动作性失败一次，权重乘以 0.9（也就是扣 10%）。演示时为了效果，暂时改为0.5
STEP_DOWN = 0.5

# 成功一次，权重加 0.1，但不能超过初始值 1.0
STEP_UP = 0.1

# 阈值：权重低于 0.35 就隔离（停止被检索）演示时为了效果，暂时改为0.4
THRESHOLD = 0.4

# 废弃线：权重掉到这个以下，就是彻底废了，不再参与任何流程
FLOOR = 0.1

# 时间冷却恢复时，恢复到这个权重（0.5，比阈值 0.35 高，所以能回到检索队列）
RESTORE_BASE = 0.5

# 同一条经验最多可以通过"时间冷却"自动恢复几次
COOLDOWN_MAX = 2


def tier_of(w):
    """
    【作用】把精确的权重数字，翻译成"高 / 中 / 低"三个档位。
    【为什么】因为精确数字不能给大模型看。如果模型知道权重是 0.9，
    攻击者就能通过诱导提问让它复述，进而反推出阈值在哪，算出"再制造几次失败就能隔离这条经验"。
    """
    if w > 0.8:
        return "高"
    if w >= 0.5:
        return "中"
    return "低"